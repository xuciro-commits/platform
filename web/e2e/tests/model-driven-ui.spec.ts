import {expect,fresh,runtime,shots,stableReadRevision,test} from './kit';

test('a model selector and start action share one capability rule',async({page,builder,operator,editor},testInfo)=>{
  test.setTimeout(120_000);
  const operation=await builder.object({title:'Operation',fields:[{name:'name',title:'Operation name',type:'text'},{name:'cut',title:'Requires cutting',type:'boolean'}]});
  const requirement={op:'path',kind:'boolean',args:[{op:'',kind:'reference',ref:'input.operation'}],path:['cut']};
  const criteria={op:'or',kind:'boolean',args:[{op:'not',kind:'boolean',args:[requirement]},{op:'',kind:'boolean',ref:'cut'}]};
  const action={name:'start',title:'Start',from:['ready'],to:'running',inputs:[{name:'operation',title:'Operation',type:'reference',ref:operation.type,required:true}],conditions:[{expr:criteria,message:'Equipment lacks required capabilities'}]};
  const equipment=await builder.object({title:'Equipment',fields:[{name:'name',title:'Equipment name',type:'text'},{name:'cut',title:'Cutting',type:'boolean'},{name:'drill',title:'Drilling',type:'boolean'}],states:[{name:'ready',title:'Ready'},{name:'running',title:'Running'}],actions:[action]});
  const operationRows=await builder.records(operation.type,[{name:'Cut operation',cut:true}]);
  const equipmentRows=await builder.records(equipment.type,[{name:'Cutter',cut:true,drill:false},{name:'Drill',cut:false,drill:true}]);
  const sections=[{id:'operations',widget:'table',configVersion:1,title:'Operations',model:{type:operation.type}},{id:'equipment',widget:'record-picker',configVersion:1,title:'Eligible equipment',model:{type:equipment.type,fields:[{name:'name',slot:'recordPicker.labelField'}],options:{rule:{action:{app:'build',kind:'action',name:`${equipment.type}.start`},inputs:{operation:'operation'}}}}}];
  const document={formatVersion:2,uiProfile:'platform.page.v2.110',root:'root',nodes:{root:{kind:'rows',children:['operations','equipment']},operations:{kind:'widget',section:'operations'},equipment:{kind:'widget',section:'equipment'}},variables:{operation:{scope:'page',type:'record',mode:'resource',source:{kind:'record',section:'operations'}}}};
  const draft=await builder.page({title:'Equipment allocation',object:operation.type,sections,document});
  await editor.open(builder,draft.id);
  await editor.select('Eligible equipment');
  await editor.inspector.getByRole('tab',{name:'Data',exact:true}).click();
  const model=editor.inspector.getByLabel('Model binding',{exact:true});
  await expect(model.getByRole('combobox',{name:'Original action criteria',exact:true})).toHaveValue(`build/${equipment.type}.start`);
  await expect(model.getByText('Candidates and the action use the same original rule. Edit it in Behavior.',{exact:true})).toBeVisible();
  await editor.release();
  const tab=await runtime(page,operator,draft.name);
  await tab.getByRole('row').filter({hasText:'Cut operation'}).click();
  await tab.getByRole('combobox',{name:'Eligible equipment',exact:true}).click();
  await expect(tab.getByRole('option',{name:/ · Cutter$/})).toBeVisible();
  await expect(tab.getByRole('option',{name:/ · Drill$/})).toHaveCount(0);
  await expect(operator.decide(`${equipment.type}.start`,{type:equipment.type,id:equipmentRows[1]!},{operation:operationRows[0]})).rejects.toThrow(/Equipment lacks required capabilities/);
  const changed={...action,conditions:[{expr:{op:'',kind:'boolean',ref:'drill'},message:'Equipment lacks required capabilities'}]};
  await builder.decide('build.object.edit',{type:'build.object',id:equipment.id},{actions:[changed]});
  await builder.decide('build.object.publish',{type:'build.object',id:equipment.id},{});
  await tab.reload();
  await tab.getByRole('row').filter({hasText:'Cut operation'}).click();
  await tab.getByRole('combobox',{name:'Eligible equipment',exact:true}).click();
  await expect(tab.getByRole('option',{name:/ · Drill$/})).toBeVisible();
  await expect(tab.getByRole('option',{name:/ · Cutter$/})).toHaveCount(0);
  await operator.decide(`${equipment.type}.start`,{type:equipment.type,id:equipmentRows[1]!},{operation:operationRows[0]});
  await shots(tab,tab.locator('body'),'model-candidates',testInfo);
  await tab.close();
});

test('legacy sections save as model bindings and a declared multi-hop field renders',async({page,builder,operator,editor},testInfo)=>{
  test.setTimeout(120_000);
  await stableReadRevision(page);
  const country=await builder.object({title:'Country',fields:[{name:'name',title:'Country name',type:'text'}]});
  const supplier=await builder.object({title:'Supplier',fields:[{name:'country',title:'Country',type:'reference',ref:country.type}]});
  const order=await builder.object({title:'Order',fields:[{name:'name',title:'Order name',type:'text'},{name:'supplier',title:'Supplier',type:'reference',ref:supplier.type}]});
  const [countryID]=await builder.records(country.type,[{name:'Canada'}]);
  const [supplierID]=await builder.records(supplier.type,[{country:countryID}]);
  await builder.records(order.type,[{name:'Order A',supplier:supplierID}]);
  const draft=await builder.page({title:'Orders',object:order.type,document:null,sections:[{id:'orders',widget:'table',configVersion:1,title:'Orders',fields:['name','supplier']}]});
  await builder.decide('build.page.publish',{type:'build.page',id:draft.id},{});
  const historical=(await operator.definitions<any>()).find(d=>d.ref.kind==='page'&&d.ref.name===draft.name);
  expect(historical.page.document).toBeUndefined();
  const tab=await runtime(page,operator,draft.name);
  await expect(tab.getByRole('cell',{name:'Order A',exact:true})).toBeVisible();
  await editor.open(builder,draft.id);
  await editor.select('Orders');
  await editor.inspector.getByRole('tab',{name:'Data',exact:true}).click();
  const model=editor.inspector.getByLabel('Model binding',{exact:true});
  await model.getByRole('button',{name:'Use model field defaults',exact:true}).click();
  await expect(model.getByText('Inferred from model',{exact:true})).toBeVisible();
  await editor.save();
  await expect.poll(async()=> (await builder.record('build.page',draft.id)).sections[0].model?.type).toBe(order.type);
  const migrated=await builder.record('build.page',draft.id);
  expect(migrated.sections[0].object).toBeUndefined();
  expect(migrated.sections[0].fields).toBeUndefined();
  expect(migrated.document.uiProfile).toBe('platform.page.v2.110');
  await editor.release();
  await tab.reload();
  await expect(tab.getByRole('cell',{name:'Order A',exact:true})).toBeVisible();
  await editor.open(builder,draft.id);
  await editor.select('Orders');
  await editor.inspector.getByRole('tab',{name:'Data',exact:true}).click();
  await model.getByRole('button',{name:'Add model field',exact:true}).click();
  const field=model.getByLabel('Declared model path',{exact:true}).last();
  await field.getByRole('combobox',{name:'Model field',exact:true}).selectOption('supplier');
  await field.getByRole('button',{name:'Follow declared reference',exact:true}).click();
  await field.getByRole('combobox',{name:'Reference hop 1',exact:true}).selectOption('country');
  await field.getByRole('button',{name:'Follow declared reference',exact:true}).click();
  await field.getByRole('combobox',{name:'Reference hop 2',exact:true}).selectOption('name');
  await editor.save();
  await expect.poll(async()=> (await builder.record('build.page',draft.id)).sections[0].model.fields?.[0]?.path).toEqual(['supplier','country','name']);
  await editor.release();
  await tab.reload();
  await expect(tab.getByRole('cell',{name:'Canada',exact:true})).toBeVisible();
  await shots(tab,tab.locator('body'),'model-path',testInfo);
	// Fail an actual declared hop after a successful read: old relationship
	// content must disappear and the owning component reports the failure.
	await tab.route(`**/v1/records/${supplier.type}/*`,route=>route.abort('failed'));
	await tab.reload();
	await expect(tab.getByText('Model binding could not be read. Check its declared source and permissions.',{exact:true})).toBeVisible();
	await expect(tab.getByRole('cell',{name:'Canada',exact:true})).toHaveCount(0);
  await tab.close();
});

test('model permissions mark a partial collection and disable an unwritable cell with its owner reason',async({page,builder,operator,editor},testInfo)=>{
  test.setTimeout(90_000);
  const object=await builder.object({title:'Scoped item',fields:[{name:'name',title:'Item name',type:'text'},{name:'note',title:'Protected note',type:'text',write:['builder']}],access:[{role:'user',read:'own',create:true,edit:true}]});
  await builder.records(object.type,[{name:'Hidden item',note:'Hidden note'}]);
  const visible=fresh('VISIBLE');
  await operator.decide(`${object.type}.create`,{type:object.type,id:visible},{name:'Visible item'});
  await builder.decide(`${object.type}.edit`,{type:object.type,id:visible},{note:'Original protected note'});
  const sections=[{id:'items',widget:'table',configVersion:1,title:'Scoped items',model:{type:object.type,visibility:'mark'},inlineEdit:{action:`${object.type}.edit`,fields:['name','note']}}];
  const document={formatVersion:2,uiProfile:'platform.page.v2.110',root:'root',nodes:{root:{kind:'rows',children:['items']},items:{kind:'widget',section:'items'}}};
  const draft=await builder.page({title:'Scoped items',object:object.type,sections,document});
  await editor.open(builder,draft.id);
  await editor.release();
  const tab=await runtime(page,operator,draft.name);
  await expect(tab.getByText('Some records or fields are outside your permissions.',{exact:true})).toBeVisible();
  await expect(tab.getByRole('cell',{name:'Visible item',exact:true})).toBeVisible();
  await expect(tab.getByRole('cell',{name:'Hidden item',exact:true})).toHaveCount(0);
  await tab.getByRole('button',{name:'Edit cells',exact:true}).click();
  const note=tab.getByRole('cell',{name:'Original protected note',exact:true});
  await expect(note).toHaveAttribute('aria-disabled','true');
  await expect(note).toHaveAttribute('title',/outside.*permissions/);
  await note.dblclick();
  await expect(note.getByRole('textbox')).toHaveCount(0);
  await shots(tab,tab.locator('body'),'model-permissions',testInfo);
  await builder.edit(draft.id,{sections:[{...sections[0],model:{type:object.type}}]});
  await builder.decide('build.page.publish',{type:'build.page',id:draft.id},{});
  await tab.reload();
  await expect(tab.getByRole('table')).toHaveCount(0);
  await tab.close();
});
