import { test, expect, slug, shots } from "./kit";

test.use({ actionTimeout: 15_000 });

test("a new administrator reviews a local package, installs it, uninstalls and removes its source", async ({ page, builder }, info) => {
  test.setTimeout(150_000);
  const id = slug("extension");
  await builder.open(page, "/apps");
  await page.getByRole("region", { name: "Packages", exact: true }).getByRole("button", { name: "Package guide", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Understand the source", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Uninstall safely", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Uninstall safely", exact: true })).toBeVisible();
  await expect(page.getByText("Uninstall removes live contributions", { exact: false })).toBeVisible();
  await page.getByRole("button", { name: "Open Packages", exact: true }).click();
  await page.getByRole("button", { name: "Add package", exact: true }).click();
  await page.getByLabel("Package source", { exact: true }).selectOption("online");
  await page.getByLabel("Package URL", { exact: true }).fill("http://example.com/package.json");
  await page.getByRole("button", { name: "Review package", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "HTTPS" })).toBeVisible();
  await page.getByLabel("Package source", { exact: true }).selectOption("file");
  const descriptor = { id, version: "1.0.0", namespace: id, title: "Reviewed extension", capabilities: [{ id: "platform.kernel", version: "1", semantics: "1" }] };
  await page.getByLabel("Package file", { exact: true }).setInputFiles({ name: "package.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(descriptor)) });
  await page.getByRole("button", { name: "Review package", exact: true }).click();
  await expect(page.getByText("Reviewed content", { exact: true })).toBeVisible();
  expect((await builder.read<any[]>("packages")).some(item => item.descriptor.id === id)).toBe(false);
  await shots(page, page.locator("body"), "package-source-review", info);
  await page.getByRole("button", { name: "Add reviewed version to library", exact: true }).click();
  await page.getByRole("region", { name: "Package library", exact: true }).getByRole("button").filter({ hasText: id }).click();
  const card = page.getByLabel(`Package ${id}`, { exact: true });
  await expect(card).toBeVisible();
  await expect(card.getByText("precheck ok", { exact: true })).toHaveCount(0);
  await card.getByRole("combobox", { name: "Exact package version", exact: true }).selectOption("1.0.0");
  await card.getByRole("button", { name: "Technical details", exact: true }).click();
  await expect(card.getByText("Imported package", { exact: true })).toBeVisible();
  await card.getByRole("button", { name: "Install", exact: true }).click();
  await expect(card.getByText("active", { exact: true })).toBeVisible();
  await card.getByRole("button", { name: "Prepare to uninstall", exact: true }).click();
  await expect(card.getByText("draining", { exact: true })).toBeVisible();
  await card.getByRole("button", { name: "Uninstall", exact: true }).click();
  await expect(card.getByText("not installed", { exact: true })).toBeVisible();
  await card.getByRole("button", { name: "Remove source", exact: true }).click();
  await expect(card.getByText("Installed record", { exact: true })).toBeVisible();
  await expect(card.getByRole("button", { name: "Remove source", exact: true })).not.toBeVisible();
  expect((await builder.read<any[]>("packages")).find(item => item.descriptor.id === id)?.installed.state).toBe("retired");
  await page.setViewportSize({ width: 390, height: 844 });
  await shots(page, page.locator("body"), "package-removed-narrow", info);
  await page.setViewportSize({ width: 1280, height: 900 });
  await builder.open(page, "/host-tenant?tenant=browser-primary");
  const composition = page.getByRole("region", { name: "Foundational capabilities", exact: true });
  await composition.getByLabel("platform.rules", { exact: true }).selectOption("");
  await composition.getByLabel("Reason", { exact: true }).fill("Verify maintenance and restore access");
  await composition.getByRole("button", { name: "Save selection and pause", exact: true }).click();
  await expect.poll(async () => (await builder.request.get("/v1/me", { headers: builder.headers })).status()).toBe(503);
  // Reload while tenant APIs are unavailable: host maintenance must still open.
  await page.goto("/#/host-tenant?tenant=browser-primary");
  await expect(composition.getByText("maintenance", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Review a package", exact: true }).click();
  await page.getByLabel("Package file", { exact: true }).setInputFiles({ name: "review.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(descriptor)) });
  await page.getByRole("button", { name: "Review package", exact: true }).click();
  await expect(page.getByText("Reviewed content", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Add reviewed version to library", exact: true })).not.toBeVisible();
  await shots(page, composition, "package-foundation-maintenance", info);
  await composition.getByRole("button", { name: "Package guide", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Foundational capabilities", exact: true })).toBeVisible();
  await page.goto("/#/host-tenant?tenant=browser-primary");
  await composition.getByLabel("platform.rules", { exact: true }).selectOption("platform.rules.native");
  await composition.getByLabel("Reason", { exact: true }).fill("Restore the compatible implementation");
  await composition.getByRole("button", { name: "Save selection and pause", exact: true }).click();
  await page.getByRole("button", { name: "Resume", exact: true }).click();
  const resume = page.getByRole("dialog", { name: "Resume browser-primary", exact: true });
  await resume.getByLabel("Reason", { exact: true }).fill("Required contracts are restored");
  await resume.getByRole("button", { name: "Confirm", exact: true }).click();
  await expect.poll(async () => (await builder.request.get("/v1/me", { headers: builder.headers })).status()).toBe(200);
  expect((await builder.read<any[]>("packages")).find(item => item.descriptor.id === id)?.installed.state).toBe("retired");

});
