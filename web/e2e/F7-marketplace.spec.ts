import type { PackageDescriptor, PackagePreview, PackageView, ResourceDirectory } from "../packages/kernel/src/gen/host";
import { acceptedClient, expect, signIn, test, unique } from "./kit";

test.use({actionTimeout:15_000});

test("F7 an administrator reviews a dependency closure, installs managed products, upgrades them and preserves customer extensions on retirement", async ({ page }) => {
  test.setTimeout(180_000);
  const source=acceptedClient(page,"publisher","publisher"), customer=acceptedClient(page);
  const tag=unique("product"), provider=`${tag}provider`, consumer=`${tag}consumer`;
  const publisherProject=unique("PUBLISHERPROJECT"), customerProject=unique("CUSTOMERPROJECT");
  const providerObject=unique("PROVIDER"), providerApp=unique("PROVIDERAPP"), consumerObject=unique("CONSUMER"), consumerApp=unique("CONSUMERAPP");
  const baseType=`build.${provider}`, customerType=`build.${tag}extension`;
  const providerTitle=`Provider ${tag}`, consumerTitle=`Consumer ${tag}`;
  const selectPackage=(title:string)=>page.getByRole("region",{name:"Package library"}).getByRole("button",{name:new RegExp(title)}).click();
  const ref=(kind:string,name:string)=>({app:"build",kind,name});
  const products=new Set<string>();
  const fields=[{name:"code",title:"Code",type:"text",required:true}];
  const confirm={name:"confirm",title:"Confirm provider",from:["open"],inputs:[{name:"description",title:"Description",type:"text",required:true}],sets:[{field:"description",from:"description"}]};
  await source.submit("build.app",publisherProject,"create",{name:publisherProject,title:"Publisher project"});
  await customer.submit("build.app",customerProject,"create",{name:customerProject,title:"Customer project"});
  await source.submit("build.object",providerObject,"create",{name:provider,title:providerTitle,project:publisherProject,fields:[...fields,{name:"description",title:"Description",type:"text"}],states:[{name:"open",title:"Open"}]});
  await source.submit("build.actiontype",`${baseType}.confirm`,"create",{name:`${baseType}.confirm`,object:baseType,project:publisherProject,definition:confirm});
  await source.submit("build.app",providerApp,"create",{name:`${provider}app`,title:providerTitle,resources:[ref("object",baseType)]});
  const freeze=async(id:string,version:string,object:string,app:string,title:string,requires:string[]=[]):Promise<PackageDescriptor>=>{
    if(!products.has(id)){
      await source.submit("build.product",id,"create",{name:id,title,project:app,roots:[ref("app",`${id}app`)],requires});
      products.add(id);
    }
    const candidate=await source.publish([{kind:"object",id:object},{kind:"app",id:app}]);
    await source.submit("build.productversion",`${id}@${version}`,"create",{product:id,version,candidate});
    return (await source.read<{record:{descriptor:PackageDescriptor}}>(`/v1/records/build.productversion/${encodeURIComponent(`${id}@${version}`)}`)).record.descriptor;
  };
  const first=await freeze(provider,"1.2.0",providerObject,providerApp,providerTitle);
  await source.submit("build.object",providerObject,"edit",{fields:[...fields,{name:"description",title:"Description",type:"text"}]});
  const action=await source.read<{record:{version:number}}>(`/v1/records/build.actiontype/${baseType}.confirm`);
  await source.submit("build.actiontype",`${baseType}.confirm`,"edit",{name:`${baseType}.confirm`,object:baseType,definition:{...confirm,title:"Confirm provider now"}},action.record.version);
  const latest=await freeze(provider,"1.10.0",providerObject,providerApp,providerTitle);
  await source.submit("build.object",consumerObject,"create",{name:consumer,title:consumerTitle,project:publisherProject,fields:[{name:"provider",title:"Provider",type:"reference",ref:baseType}]});
  await source.submit("build.app",consumerApp,"create",{name:`${consumer}app`,title:consumerTitle,resources:[ref("object",`build.${consumer}`)]});
  const dependent=await freeze(consumer,"1.0.0",consumerObject,consumerApp,consumerTitle,[`${provider}@^1.0.0`]);
  const offer=async(descriptor:PackageDescriptor)=>{
    const response=await page.request.post("/v1/packages/inspect",{headers:customer.headers,data:{content:descriptor}});
    expect(response.ok(),await response.text()).toBeTruthy();
    const inspected=await response.json() as PackagePreview;
    await customer.submit("platform.package",descriptor.id,"import",{id:descriptor.id,digest:inspected.digest},null);
  };
  await offer(first);await offer(latest);await offer(dependent);
  await signIn(page,"admin","/apps");
  await selectPackage(consumerTitle);
  const panel=page.getByRole("region",{name:`Package ${consumer}`});
  await panel.getByRole("button",{name:"Install",exact:true}).click();
  const install=page.getByRole("dialog",{name:"Review installation",exact:true});
  await expect(install.getByRole("list",{name:"Installation order"})).toContainText("1.10.0");
  await expect(install.getByRole("list",{name:"Installation order"}).getByRole("listitem")).toHaveCount(2);
  await install.getByRole("button",{name:"Install",exact:true}).click();
  await expect(install).toBeHidden();
  const installed=await customer.read<PackageView[]>("/v1/packages");
  expect(installed.find(item=>item.descriptor.id===provider)?.installed?.version).toBe("1.10.0");
  expect(installed.find(item=>item.descriptor.id===consumer)?.installed?.version).toBe("1.0.0");
  const directory=await customer.read<ResourceDirectory>("/v1/resources");
  const base=directory.resources.find(resource=>resource.ref.name===baseType && resource.ref.kind==="object")!;
  expect(base.managedBy).toBe(provider);expect(base.project).toBe(`package:${provider}`);expect(base.canEdit).toBe(false);
  const extension=unique("EXTENSION");
  await customer.submit("build.object",extension,"create",{name:`${tag}extension`,title:"Customer extension",project:customerProject,extends:baseType,fields:[{name:"base",title:"Base",type:"reference",ref:baseType,required:true},{name:"note",title:"Note",type:"text"}]});
  await customer.publish([{kind:"object",id:extension}]);
  const baseRecord=unique("BASE"), extensionRecord=unique("LOCAL");
  await customer.submit(baseType,baseRecord,"create",{code:"CUSTOMER"});
  await customer.submit(baseType,baseRecord,"confirm",{description:"Confirmed"});
  expect((await customer.read<{record:{description:string}}>(`/v1/records/${baseType}/${baseRecord}`)).record.description).toBe("Confirmed");
  await customer.submit(customerType,extensionRecord,"create",{base:baseRecord,note:"Keep my extension"});
  await source.submit("build.object",providerObject,"edit",{fields:[...fields,{name:"description",title:"Description",type:"text"},{name:"enabled",title:"Enabled",type:"boolean"}]});
  const update=await freeze(provider,"1.11.0",providerObject,providerApp,providerTitle);
  await offer(update);
  await page.goto("/#/apps?tab=updates");
  await selectPackage(providerTitle);
  const updatePanel=page.getByRole("region",{name:`Package ${provider}`});
  await updatePanel.getByRole("button",{name:"Upgrade to 1.11.0",exact:true}).click();
  const upgrade=page.getByRole("dialog",{name:"Review upgrade",exact:true});
  await expect(upgrade).toContainText("1.10.0");
  await upgrade.getByRole("button",{name:"Upgrade",exact:true}).click();
  await expect(upgrade).toBeHidden();
  expect((await customer.read<{record:{note:string}}>(`/v1/records/${customerType}/${extensionRecord}`)).record.note).toBe("Keep my extension");
  await page.goto("/#/apps?tab=catalog");
  await selectPackage(providerTitle);
  const downgradePanel=page.getByRole("region",{name:`Package ${provider}`});
  await downgradePanel.getByRole("combobox",{name:"Exact package version"}).selectOption("1.2.0");
  await downgradePanel.getByRole("button",{name:"Downgrade to 1.2.0",exact:true}).click();
  const downgrade=page.getByRole("dialog",{name:"Review downgrade",exact:true});
  await downgrade.getByRole("button",{name:"Downgrade",exact:true}).click();
  await expect(downgrade).toBeHidden();
  expect((await customer.read<PackageView[]>("/v1/packages")).find(view=>view.descriptor.id===provider)?.installed?.version).toBe("1.2.0");
  await page.goto("/#/apps?tab=catalog");
  await selectPackage(providerTitle);
  await downgradePanel.getByRole("combobox",{name:"Exact package version"}).selectOption("1.11.0");
  await downgradePanel.getByRole("button",{name:"Roll back to 1.11.0",exact:true}).click();
  const restore=page.getByRole("dialog",{name:"Review rollback",exact:true});
  await restore.getByRole("button",{name:"Roll back",exact:true}).click();
  await expect(restore).toBeHidden();
  expect((await customer.read<PackageView[]>("/v1/packages")).find(view=>view.descriptor.id===provider)?.installed?.version).toBe("1.11.0");
  await page.goto("/#/apps?tab=installed");
  await selectPackage(consumerTitle);
  await panel.getByRole("button",{name:"Mark for uninstall",exact:true}).click();
  await panel.getByRole("button",{name:"Retire",exact:true}).click();
  const uninstall=page.getByRole("dialog",{name:"Review retirement",exact:true});
  await uninstall.getByRole("button",{name:"Retire",exact:true}).click();
  await expect(uninstall).toBeHidden();
  expect((await customer.read<{record:{note:string}}>(`/v1/records/${customerType}/${extensionRecord}`)).record.note).toBe("Keep my extension");
  const retired=await customer.read<ResourceDirectory>("/v1/resources");
  expect(retired.resources.filter(resource=>resource.managedBy===consumer).every(resource=>resource.state==="archived")).toBeTruthy();
  const consumerSource=(await customer.read<PackageView[]>("/v1/packages")).find(view=>view.descriptor.id===consumer);
  expect(consumerSource?.sourceDigest).toBeTruthy();
  await customer.submit("platform.package",consumer,"remove-source",{id:consumer,digest:consumerSource!.sourceDigest},null);
  await page.goto("/#/apps?tab=retired");
  await selectPackage(consumerTitle);
  const retiredPanel=page.getByRole("region",{name:`Package ${consumer}`});
  await expect(retiredPanel.getByRole("button",{name:"Reinstall",exact:true})).toBeVisible();
  await retiredPanel.getByRole("button",{name:"Reinstall",exact:true}).click();
  const reinstall=page.getByRole("dialog",{name:"Review installation",exact:true});
  await reinstall.getByRole("button",{name:"Install",exact:true}).click();
  await expect(reinstall).toBeHidden();
  expect((await customer.read<PackageView[]>("/v1/packages")).find(view=>view.descriptor.id===consumer)?.installed?.state).toBe("active");
  expect((await customer.read<{record:{note:string}}>(`/v1/records/${customerType}/${extensionRecord}`)).record.note).toBe("Keep my extension");
  await page.goto("/#/apps?tab=installed");
  await selectPackage(consumerTitle);
  await panel.getByRole("button",{name:"Mark for uninstall",exact:true}).click();
  await panel.getByRole("button",{name:"Retire",exact:true}).click();
  await uninstall.getByRole("button",{name:"Retire",exact:true}).click();
  await expect(uninstall).toBeHidden();
  const replacement=unique("REPLACEMENT"), replacementType=`${provider}replacement`;
  await source.submit("build.object",replacement,"create",{name:replacementType,title:"Replacement provider",project:publisherProject,fields});
  await source.submit("build.app",providerApp,"edit",{resources:[ref("object",`build.${replacementType}`)]});
  const removedBase=await freeze(provider,"1.12.0",replacement,providerApp,providerTitle);
  await offer(removedBase);
  await page.goto("/#/apps?tab=updates");
  await selectPackage(providerTitle);
  await updatePanel.getByRole("button",{name:"Upgrade to 1.12.0",exact:true}).click();
  const removal=page.getByRole("dialog",{name:"Review upgrade",exact:true});
  await expect(removal.getByRole("region",{name:"References affected by removal"})).toContainText(customerType);
  await expect(removal.getByRole("button",{name:"Upgrade",exact:true})).toBeDisabled();
  const identity=await customer.read<{tenantId:string;principalId:string}>("/v1/me");
  const rejected=await page.request.post("/v1/submissions",{headers:customer.headers,data:{tenantId:identity.tenantId,principalId:identity.principalId,authority:"platform",target:{type:"platform.package",id:provider},schema:{name:"platform.package.upgrade",version:1},idempotencyKey:unique("remove"),payload:Buffer.from(JSON.stringify({id:provider,version:"1.12.0"})).toString("base64")}});
  const refusal=await rejected.json();
  expect(refusal.error).toBeDefined();
  expect(JSON.stringify(refusal)).toContain("references");
  expect((await customer.read<PackageView[]>("/v1/packages")).find(view=>view.descriptor.id===provider)?.installed?.version).toBe("1.11.0");
  await removal.getByRole("button",{name:"Cancel",exact:true}).click();
  await page.goto("/#/apps?tab=installed");
  await selectPackage(providerTitle);
  await updatePanel.getByRole("button",{name:"Mark for uninstall",exact:true}).click();
  await updatePanel.getByRole("button",{name:"Retire",exact:true}).click();
  await expect(uninstall.getByRole("region",{name:"References affected by removal"})).toContainText(customerType);
  await uninstall.getByRole("button",{name:"Retire",exact:true}).click();
  await expect(uninstall).toBeHidden();
  expect((await customer.read<{record:{note:string}}>(`/v1/records/${customerType}/${extensionRecord}`)).record.note).toBe("Keep my extension");
});
