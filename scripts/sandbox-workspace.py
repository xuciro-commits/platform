#!/usr/bin/env python3
"""Builds the offline Go workspace a sandbox needs, and nothing else.

The repository composes one host from many modules (contract, capabilities, apps,
protocols, solutions). Only `capabilities/server` commits a vendor directory, so
`go build` of a solution normally resolves the other modules over the network —
which an offline proxy sandbox does not have (AGENTS.md).

This script gives `go build` everything it needs without touching the checkout:

  .build/sandbox/go.work        every module of the repository, so all module
                                sources stay the repository's own files
  .build/sandbox/vendor/        the committed dependencies of
                                capabilities/server/vendor, symlinked, plus a
                                modules.txt that also marks the local modules
                                the workspace's go.mod files require
  .build/sandbox/env.sh         the exports (GOWORK, GOFLAGS=-mod=vendor, ...)

Run it through scripts/sandbox-go.sh, which also restores the Go toolchain.
Not a development entry point: nothing in the repository's normal flow reads
these files, and `make lite` picks them up only when they exist.
"""
import os
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SANDBOX = ROOT / ".build/sandbox"
HOST_VENDOR = ROOT / "capabilities/server/vendor"
SKIP = {"vendor", "node_modules", ".build", ".lake", ".git", "target"}

REQUIRE_BLOCK = re.compile(r"^require\s*\((.*?)^\)", re.S | re.M)
REQUIRE_LINE = re.compile(r"^require\s+(\S+)\s+(v\S+)", re.M)
REQUIRE_ENTRY = re.compile(r"^\s*(\S+)\s+(v\S+)(?:\s*//.*)?$", re.M)


def go_mod_files():
    """Every module of the repository: a go.mod outside the ignored trees."""
    for path in sorted(ROOT.rglob("go.mod")):
        if SKIP & set(path.relative_to(ROOT).parts):
            continue
        yield path


def read_module(go_mod):
    text = go_mod.read_text()
    path = re.search(r"^module\s+(\S+)", text, re.M).group(1)
    version = re.search(r"^go\s+(\S+)", text, re.M).group(1)
    requires = {}
    for block in REQUIRE_BLOCK.findall(text):
        for name, ver in REQUIRE_ENTRY.findall(block):
            requires[name] = ver
    for name, ver in REQUIRE_LINE.findall(text):
        requires[name] = ver
    return path, version, requires


def main():
    modules = {}  # module path -> (directory, go version)
    for go_mod in go_mod_files():
        path, version, _ = read_module(go_mod)
        modules[path] = (go_mod.parent, version)

    # Which local modules are required by some local module? Those are the ones
    # vendor/modules.txt must mark explicit, with the version go.mod names.
    required = {}
    for go_mod in go_mod_files():
        _, _, requires = read_module(go_mod)
        for name, ver in requires.items():
            if name not in modules:
                continue
            if required.get(name, ver) != ver:
                sys.exit(f"sandbox: {name} is required as both {required[name]} and {ver}")
            required[name] = ver

    # The vendor tree: symlink the committed dependencies by their top-level
    # module path, skipping the paths a local module owns.
    owned = {path.split("/")[0] for path in modules if "/" not in path}
    vendor = SANDBOX / "vendor"
    if vendor.exists():
        for entry in vendor.iterdir():
            entry.unlink()
    vendor.mkdir(parents=True, exist_ok=True)
    for entry in sorted(HOST_VENDOR.iterdir()):
        if entry.name == "modules.txt" or entry.name in owned:
            continue
        os.symlink(os.path.relpath(entry, vendor), vendor / entry.name)

    # modules.txt: the host's own list, without the paths a local module owns,
    # plus one explicit line per required local module (go mod vendor's format).
    lines = ["## workspace"]
    for line in (HOST_VENDOR / "modules.txt").read_text().splitlines():
        first = line[2:].split()[0] if line.startswith("# ") else line
        if first.split("/")[0] in owned:
            continue
        lines.append(line)
    for path in sorted(required):
        directory, version = modules[path]
        lines.append(f"# {path} {required[path]} => {os.path.relpath(directory, SANDBOX)}")
        lines.append(f"## explicit; go {version}")
    (vendor / "modules.txt").write_text("\n".join(lines) + "\n")

    # go.work: every module, so that building a solution uses the repository's
    # own sources for all of them (paths are relative to the file).
    uses = [f"\t{os.path.relpath(directory, SANDBOX)}" for directory, _ in modules.values()]
    (SANDBOX / "go.work").write_text("go 1.27.1\n\nuse (\n" + "\n".join(sorted(uses)) + "\n)\n")

    toolchain = pathlib.Path(os.environ.get("GOROOT", "/home/user/.go-toolchain/go"))
    (SANDBOX / "env.sh").write_text(
        "# Generated by scripts/sandbox-workspace.py; source it, do not edit.\n"
        f'export PATH="{ROOT}/tools/bin:{toolchain}/bin:$PATH"\n'
        "export GOFLAGS=-mod=vendor\n"
        "export GOTOOLCHAIN=local\n"
        "export GOPROXY=off\n"
        "export GOPATH=/home/user/.gopath\n"
        "export GOCACHE=/home/user/.gocache\n"
        f'export GOWORK="{SANDBOX}/go.work"\n'
    )
    print(f"sandbox: workspace in {SANDBOX.relative_to(ROOT)} "
          f"({len(modules)} modules, {len(required)} required locally)")


if __name__ == "__main__":
    main()
