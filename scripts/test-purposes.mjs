export function testPurpose(name) {
  const [root, ...parts] = name.split("/");
  const key = root.replace(/^Test(?:Invariant)?/, "");
  const description = descriptions.get(key);
  if (!description) throw Error("测试缺少用途说明：" + root + "（scripts/test-purposes.mjs）");
  return description + (parts.length ? " / " + parts.map(part => subcases[part] ?? part.replaceAll("_", " ")).join(" / ") : "");
}
