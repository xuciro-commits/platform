package platformserver

// rootDomains names the owner of every file in this package, by filename
// prefix. `scripts/architecture.py` requires each prefix in the directory to
// appear here and each entry here to still have files, so this package cannot
// grow a file whose responsibility nobody has claimed — the way it grew 116
// single-use prefixes while every individual file still looked reasonable.
//
// A domain is a responsibility, not a directory: these files share one package
// because they share the tenant's lock obligations and the accepted-result
// pipeline. When a domain's files stop sharing that, it becomes its own
// package and leaves this table.
